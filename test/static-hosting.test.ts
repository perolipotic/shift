import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

/**
 * AD-14 — a static SPA with no server. A deep link therefore cannot be routed
 * server-side, so the host must answer every unmatched path with index.html at
 * HTTP 200. A redirect status would break client-side routing instead of
 * fixing it, which is the failure this asserts against.
 *
 * The build-output assertions need a build. They use `it.skipIf` rather
 * than an early `return`, so a clean checkout reports them as skipped instead
 * of reporting green having asserted nothing.
 */

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const dist = join(repoRoot, 'apps', 'web', 'dist');
const SPA_FALLBACK = /^\/\*\s+\/index\.html\s+(\d{3})\s*$/m;

const notBuilt = !existsSync(dist);

/**
 * Everything a static SPA build is allowed to emit.
 *
 * An allowlist, not a denylist: a denylist of known SSR artifact names passes
 * for any artifact named something else, which is precisely the case that
 * matters — the first framework or plugin to emit a server bundle will not be
 * one of the four names we thought to write down.
 */
const PERMITTED_DIST_ENTRIES = new Set([
  'index.html', // the SPA shell
  'assets', // hashed js/css/media
  '_redirects', // the Cloudflare Pages SPA fallback, copied from public/
  '_headers', // the Cloudflare Pages security headers, copied from public/
  'favicon.svg', // the tab icon `index.html` links, copied from public/
  // STORY 8.1. The installable PWA: client-side files only, so AD-14 holds.
  'site.webmanifest', // the web manifest, generated by vite-plugin-pwa
  'sw.js', // the generated service worker (generateSW)
  'apple-touch-icon-180x180.png', // the iOS home-screen icon `index.html` links
  'pwa-192x192.png', // the manifest's icons, generated once from favicon.svg
  'pwa-512x512.png',
  'maskable-icon-512x512.png',
]);

/** Workbox's runtime, which `sw.js` imports; its name carries a content hash. */
const WORKBOX_RUNTIME = /^workbox-[\w-]+\.js$/;

/**
 * The security headers every path must carry, as `name: value` pairs.
 *
 * NO CONTENT-SECURITY-POLICY, on purpose: its `connect-src` needs the deployed
 * Supabase origin, and a policy nothing can verify against a real host is one
 * that can silently break every request the SPA makes. The entry stays open in
 * `deferred-work.md` as "CSP pending a deployed origin to verify against".
 */
const SECURITY_HEADERS: Readonly<Record<string, RegExp>> = {
  'X-Content-Type-Options': /^nosniff$/,
  'Referrer-Policy': /^strict-origin-when-cross-origin$/,
  'X-Frame-Options': /^DENY$/,
  // RESTRICTIVE: every feature it names is switched off, and the powerful
  // ones the SPA never uses are named.
  'Permissions-Policy': /^(?=.*\bcamera=\(\))(?=.*\bmicrophone=\(\))(?=.*\bgeolocation=\(\))(?=.*\bpayment=\(\))(?=.*\busb=\(\))[a-z-]+=\(\)(, [a-z-]+=\(\))*$/,
};

/** The headers of the `/*` block in a `_headers` file, keyed by lowercase name. */
function headersForAllPaths(file: string): Map<string, string> {
  const headers = new Map<string, string>();
  let inAllPaths = false;

  for (const line of file.split('\n')) {
    if (line.trim() === '' || line.trimStart().startsWith('#')) continue;
    if (!/^\s/.test(line)) {
      inAllPaths = line.trim() === '/*';
      continue;
    }
    if (!inAllPaths) continue;
    const separator = line.indexOf(':');
    if (separator === -1) continue;
    headers.set(line.slice(0, separator).trim().toLowerCase(), line.slice(separator + 1).trim());
  }

  return headers;
}

/**
 * Every header line outside the `/*` block, and every `! Name` detach anywhere.
 *
 * Cloudflare Pages applies EVERY matching block, so a later `/app/*` block
 * that sets `X-Frame-Options: SAMEORIGIN`, or detaches it with
 * `! X-Frame-Options`, silently weakens the rule for those paths. Nothing may
 * touch a security header except the `/*` block.
 */
function securityOverrides(file: string): string[] {
  const guarded = new Set(Object.keys(SECURITY_HEADERS).map((name) => name.toLowerCase()));
  const found: string[] = [];
  let block = '';

  for (const line of file.split('\n')) {
    if (line.trim() === '' || line.trimStart().startsWith('#')) continue;
    if (!/^\s/.test(line)) {
      block = line.trim();
      continue;
    }
    const entry = line.trim();
    const detached = entry.startsWith('!');
    const name = (detached ? entry.slice(1) : entry.split(':')[0] ?? '').trim().toLowerCase();

    if (detached || (block !== '/*' && guarded.has(name))) found.push(`${block}: ${entry}`);
  }

  return found;
}

function assertSecurityHeaders(file: string): void {
  const headers = headersForAllPaths(file);

  expect(securityOverrides(file), 'a block removes or overrides a security header').toEqual([]);

  for (const [name, expected] of Object.entries(SECURITY_HEADERS)) {
    const value = headers.get(name.toLowerCase());

    expect(value, `${name} is missing from the /* block`).toBeDefined();
    expect(value, `${name} has the wrong value`).toMatch(expected);
  }
}

describe('static host SPA fallback', () => {
  it('serves every client route from index.html with status 200', () => {
    const redirects = readFileSync(join(repoRoot, 'apps', 'web', 'public', '_redirects'), 'utf8');
    const match = SPA_FALLBACK.exec(redirects);

    expect(match, `_redirects has no SPA fallback rule:\n${redirects}`).not.toBeNull();
    expect(match?.[1]).toBe('200');
  });

  it.skipIf(notBuilt)('ships the fallback rule into the build output', () => {
    // Vite copies public/ verbatim, so this catches a publicDir misconfiguration.
    const built = join(dist, '_redirects');

    expect(existsSync(built), `${built} is missing from the build output`).toBe(true);
    expect(SPA_FALLBACK.test(readFileSync(built, 'utf8'))).toBe(true);
  });

  it('carries every security header on every path', () => {
    const file = join(repoRoot, 'apps', 'web', 'public', '_headers');

    expect(existsSync(file), `${file} is missing`).toBe(true);
    assertSecurityHeaders(readFileSync(file, 'utf8'));
  });

  it('catches a block that removes or overrides a security header', () => {
    const base = readFileSync(join(repoRoot, 'apps', 'web', 'public', '_headers'), 'utf8');

    expect(securityOverrides(base)).toEqual([]);
    expect(securityOverrides(`${base}\n/app/*\n  ! X-Frame-Options\n`)).toHaveLength(1);
    expect(securityOverrides(`${base}\n/app/*\n  X-Frame-Options: SAMEORIGIN\n`)).toHaveLength(1);
    expect(securityOverrides(`${base}\n/assets/*\n  Cache-Control: max-age=31536000\n`)).toEqual([]);
  });

  it.skipIf(notBuilt)('ships the security headers into the build output', () => {
    const built = join(dist, '_headers');

    expect(existsSync(built), `${built} is missing from the build output`).toBe(true);
    assertSecurityHeaders(readFileSync(built, 'utf8'));
  });

  it.skipIf(notBuilt)('emits nothing but the static shell, its assets and the fallback', () => {
    const emitted = readdirSync(dist).sort();

    expect(emitted).toContain('index.html');
    expect(
      emitted.filter((entry) => !PERMITTED_DIST_ENTRIES.has(entry) && !WORKBOX_RUNTIME.test(entry)),
    ).toEqual([]);
  });
});

/**
 * A source map holds the whole original source, comments included. The build
 * keeps it for decoding a stack trace (`sourcemap: 'hidden'`), but no chunk
 * points at it and the deploy deletes it before upload (DEPLOY.md §4).
 */
describe('source maps stay off the CDN', () => {
  it('builds them hidden', () => {
    const config = readFileSync(join(repoRoot, 'apps', 'web', 'vite.config.ts'), 'utf8');

    expect(config).toMatch(/^\s*sourcemap: 'hidden',$/m);
  });

  it('deletes every map from the upload before the deploy publishes it', () => {
    const action = readFileSync(join(repoRoot, '.github', 'actions', 'deploy', 'action.yml'), 'utf8');
    const deleted = action.indexOf("find apps/web/dist -name '*.map' -type f -delete");
    const published = action.indexOf('wrangler pages deploy apps/web/dist');

    expect(deleted).toBeGreaterThan(-1);
    expect(published).toBeGreaterThan(deleted);
  });

  it.skipIf(notBuilt)('no built chunk names its map', () => {
    const assets = join(dist, 'assets');
    const chunks = readdirSync(assets).filter((name) => /\.(js|css)$/.test(name));

    expect(chunks.length, 'expected at least one built chunk').toBeGreaterThan(0);
    for (const chunk of chunks) {
      expect(readFileSync(join(assets, chunk), 'utf8'), chunk).not.toContain('sourceMappingURL');
    }
  });
});

/**
 * Story 8.1: the app installs as a PWA. The manifest and the service worker are
 * generated by `vite-plugin-pwa` at build time, so they are asserted off the
 * build output rather than off a source file.
 */
describe('the build is an installable PWA', () => {
  const read = (name: string): string => readFileSync(join(dist, name), 'utf8');
  const workboxRuntimes = (): string[] => readdirSync(dist).filter((entry) => WORKBOX_RUNTIME.test(entry));

  it.skipIf(notBuilt)('ships a manifest named "Shift", in Croatian, standalone from /', () => {
    const manifest = JSON.parse(read('site.webmanifest')) as Record<string, unknown>;

    expect(manifest).toMatchObject({
      name: 'Shift',
      short_name: 'Shift',
      lang: 'hr',
      start_url: '/',
      display: 'standalone',
      theme_color: '#e8edf5',
      background_color: '#e8edf5',
    });
  });

  it.skipIf(notBuilt)('lists 192, 512 and maskable 512 icons, and ships every one', () => {
    const manifest = JSON.parse(read('site.webmanifest')) as {
      icons: { src: string; sizes: string; type: string; purpose?: string }[];
    };
    const icons = manifest.icons.map(({ sizes, type, purpose }) => `${sizes} ${type} ${purpose ?? 'any'}`);

    expect(icons).toEqual(
      expect.arrayContaining(['192x192 image/png any', '512x512 image/png any', '512x512 image/png maskable']),
    );
    for (const icon of manifest.icons) {
      expect(existsSync(join(dist, icon.src.replace(/^\//, ''))), `${icon.src} is missing`).toBe(true);
    }
    expect(existsSync(join(dist, 'apple-touch-icon-180x180.png'))).toBe(true);
  });

  it.skipIf(notBuilt)('links the manifest and the apple-touch-icon once each', () => {
    const page = read('index.html');

    expect(page.match(/<link\b[^>]*\brel="manifest"[^>]*>/g) ?? []).toHaveLength(1);
    expect(page).toMatch(/<link\b[^>]*\bhref="\/site\.webmanifest"/);
    expect(page.match(/<link\b[^>]*\brel="apple-touch-icon"[^>]*>/g) ?? []).toHaveLength(1);
  });

  it.skipIf(notBuilt)('precaches the shell and falls back to index.html for navigations', () => {
    const worker = read('sw.js');

    expect(worker).toMatch(/url:\s*"index\.html"/);
    expect(worker).toMatch(/url:\s*"site\.webmanifest"/);
    expect(worker).toMatch(/createHandlerBoundToURL\(\s*"\/index\.html"\s*\)/);
  });

  it.skipIf(notBuilt)('precaches the entry chunk and every stylesheet the page loads', () => {
    // Workbox silently drops a file over `maximumFileSizeToCacheInBytes`
    // (2 MiB by default), and the entry chunk is already ~1.4 MB: without
    // this, the shell would stop working offline with a green build.
    const page = read('index.html');
    const worker = read('sw.js');
    // Each tag's attributes read on their own, in any order and either quote,
    // as `localization-applied.test.ts` reads the entry chunk.
    const attributesOf = (tag: string): Map<string, string> =>
      new Map(
        [...tag.matchAll(/([\w-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g)].map((found) => [
          (found[1] ?? '').toLowerCase(),
          found[2] ?? found[3] ?? '',
        ]),
      );
    const tags = (name: string): Map<string, string>[] =>
      [...page.matchAll(new RegExp(`<${name}\\b([^>]*)>`, 'gi'))].map((found) => attributesOf(found[1] ?? ''));
    const entry = tags('script')
      .filter((attributes) => attributes.get('type') === 'module' && attributes.has('src'))
      .map((attributes) => attributes.get('src') ?? '');
    const stylesheets = tags('link')
      .filter((attributes) => attributes.get('rel') === 'stylesheet')
      .map((attributes) => attributes.get('href') ?? '');

    expect(entry, 'expected exactly one module script on the built page').toHaveLength(1);
    expect(stylesheets.length, 'expected at least one stylesheet on the built page').toBeGreaterThan(0);
    for (const src of [...entry, ...stylesheets]) {
      const path = src.replace(/^\.?\//, '');

      expect(path).toMatch(/^assets\//);
      expect(worker, `${path} is not precached`).toContain(`url:"${path}"`);
    }
  });

  it.skipIf(notBuilt)('caches nothing at runtime: Supabase always goes to the network', () => {
    const worker = read('sw.js');

    expect(worker).not.toMatch(/supabase/i);
    // The only route is the navigation fallback; a runtime cache would add a
    // strategy (`NetworkFirst`, `CacheFirst`, `StaleWhileRevalidate`...).
    expect(worker.match(/registerRoute\(/g) ?? []).toHaveLength(1);
    expect(worker).not.toMatch(/NetworkFirst|NetworkOnly|CacheFirst|CacheOnly|StaleWhileRevalidate/);
  });

  it.skipIf(notBuilt)('never activates a new worker without the member', () => {
    const worker = read('sw.js');

    // `prompt` mode: `skipWaiting` only answers the SKIP_WAITING message that
    // *Osvježi* sends, never runs on install.
    expect(worker).toMatch(/"SKIP_WAITING"\s*===\s*\w+\.data\.type\s*&&\s*self\.skipWaiting\(\)/);
    expect(worker.match(/skipWaiting\(\)/g) ?? []).toHaveLength(1);
    expect(worker).not.toContain('clientsClaim');
  });

  it.skipIf(notBuilt)('names no sourcemap in the worker or its runtime', () => {
    const files = ['sw.js', ...workboxRuntimes()];

    expect(workboxRuntimes(), 'expected the workbox runtime beside sw.js').toHaveLength(1);
    for (const file of files) {
      expect(read(file), file).not.toContain('sourceMappingURL');
      expect(existsSync(join(dist, `${file}.map`)), `${file}.map was built`).toBe(false);
    }
  });
});
